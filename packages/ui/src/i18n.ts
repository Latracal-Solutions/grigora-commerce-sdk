export type UIStrings = typeof EN;
export type StringKey = keyof UIStrings;

export function translator(overrides: Partial<UIStrings> = {}) {
  const table: UIStrings = { ...EN, ...overrides };
  return (key: StringKey, vars: Record<string, string | number> = {}): string => {
    const template = table[key] ?? EN[key] ?? String(key);
    return template.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] === undefined ? "" : String(vars[name])));
  };
}

export type Translate = ReturnType<typeof translator>;
